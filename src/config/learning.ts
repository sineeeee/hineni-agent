export const fieldLessons: Record<string, FieldLesson> = {};
function add(group: string, text: string) {
  for (const line of text.trim().split("\n")) {
    const [key, title, meaning, effect, when] = line.split("|");
    if (!key || !title || !meaning || !effect)
      throw Error("Incomplete explanation: " + group + "." + key);
    fieldLessons[group + "." + key] = {
      title,
      meaning,
      effect,
      when: when || learningStages[group],
    };
  }
}
